#!/usr/bin/env node
// Self-hosted Charis subset (D-36). Fontsource's Charis subsets drop combining marks and
// modifier letters that real nation names use (e.g. Ql̓ispé, ʷ, ⁿ), so we subset the full
// SIL release instead. Run once after changing the ranges: node scripts/build-fonts.mjs
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { mkdirSync, mkdtempSync, readFileSync, writeFileSync, copyFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import subsetFont from 'subset-font';

const ZIP_URL = 'https://software.sil.org/downloads/r/charis/Charis-7.000.zip';
const ZIP_SHA256 = 'e3237b1303c5d31af8f59b1d1914886c5e873b77c71390e4742fb3bc1c187666';
const OUT = 'public/fonts';
// Basic Latin, Latin-1, Latin Extended A/B, IPA, spacing modifiers, combining marks, Greek basic
// (for scholarly citations), Latin Extended Additional, general punctuation, super/subscripts,
// currency, letterlike, arrows minimal, Latin Extended C/D/E.
const RANGES = [
  [0x20, 0x7e],
  [0xa0, 0x24f],
  [0x250, 0x2af],
  [0x2b0, 0x2ff],
  [0x300, 0x36f],
  [0x370, 0x3ff],
  [0x1d00, 0x1dbf],
  [0x1dc0, 0x1dff],
  [0x1e00, 0x1eff],
  [0x2000, 0x206f],
  [0x2070, 0x209f],
  [0x20a0, 0x20bf],
  [0x2100, 0x214f],
  [0x2c60, 0x2c7f],
  [0xa720, 0xa7ff],
  [0xab30, 0xab6f],
];
const CORE = [
  [0x20, 0x7e],
  [0xa0, 0xff],
  [0x2000, 0x206f],
  [0x20ac, 0x20ac],
  [0x2122, 0x2122],
];
const inRanges = (cp, rs) => rs.some(([a, b]) => cp >= a && cp <= b);
const chars = (rs, keep) =>
  rs
    .flatMap(([a, b]) => Array.from({ length: b - a + 1 }, (_, i) => a + i))
    .filter(keep)
    .map((cp) => String.fromCodePoint(cp))
    .join('');
const SUBSETS = {
  core: chars(CORE, () => true),
  ext: chars(RANGES, (cp) => !inRanges(cp, CORE)),
};
const unicodeRange = (rs) =>
  rs
    .map(([a, b]) => (a === b ? `U+${a.toString(16)}` : `U+${a.toString(16)}-${b.toString(16)}`))
    .join(',');
const extRanges = RANGES.flatMap(([a, b]) => {
  // RANGES minus CORE, as ranges, for the CSS unicode-range of the ext files
  const out = [];
  let start = null;
  for (let cp = a; cp <= b + 1; cp++) {
    const inside = cp <= b && !inRanges(cp, CORE);
    if (inside && start === null) start = cp;
    if (!inside && start !== null) {
      out.push([start, cp - 1]);
      start = null;
    }
  }
  return out;
});
const STYLES = {
  Regular: ['regular', 400, 'normal'],
  Italic: ['italic', 400, 'italic'],
  Bold: ['bold', 700, 'normal'],
  BoldItalic: ['bold-italic', 700, 'italic'],
};

const res = await fetch(ZIP_URL);
if (!res.ok) throw new Error(`HTTP ${res.status} for ${ZIP_URL}`);
const zip = Buffer.from(await res.arrayBuffer());
const sum = createHash('sha256').update(zip).digest('hex');
if (sum !== ZIP_SHA256) throw new Error(`checksum mismatch for Charis zip: ${sum}`);
const dir = mkdtempSync(join(tmpdir(), 'charis-'));
writeFileSync(join(dir, 'c.zip'), zip);
execFileSync('unzip', ['-q', '-o', join(dir, 'c.zip'), '-d', dir]);
mkdirSync(join(OUT, 'LICENSES'), { recursive: true });
const css = ['/* Generated by scripts/build-fonts.mjs. Charis 7.000 (SIL, OFL 1.1), subset. */'];
for (const [src, [name, weight, style]] of Object.entries(STYLES)) {
  const ttf = readFileSync(join(dir, 'Charis-7.000', `Charis-${src}.ttf`));
  for (const [part, text] of Object.entries(SUBSETS)) {
    const woff2 = await subsetFont(ttf, text, { targetFormat: 'woff2' });
    const file = `charis-${name}-${part}.woff2`;
    writeFileSync(join(OUT, file), woff2);
    console.log(`${file} ${(woff2.length / 1024).toFixed(0)} KB`);
    css.push(
      `@font-face{font-family:'Charis';font-style:${style};font-weight:${weight};font-display:swap;src:url('./${file}') format('woff2');unicode-range:${unicodeRange(part === 'core' ? CORE : extRanges)};}`,
    );
  }
}
writeFileSync(join(OUT, 'charis.css'), css.join('\n') + '\n');
copyFileSync(join(dir, 'Charis-7.000', 'OFL.txt'), join(OUT, 'LICENSES', 'Charis-OFL.txt'));
