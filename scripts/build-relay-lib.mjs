// Bundles the atlas logic the relay's MCP server shares with the site (src/lib/where.ts,
// support.ts, routes.ts) into relay/lib/atlas.gen.js, a single plain-ESM file Node can load on
// Vercel. Run after changing those files; `--check` fails if the committed bundle is stale (CI).
import { build } from 'esbuild';
import { readFileSync, writeFileSync } from 'node:fs';

const OUT = 'relay/lib/atlas.gen.js';
const result = await build({
  stdin: {
    contents: `export { placeReport } from './src/lib/where.ts';
export { supportFor } from './src/lib/support.ts';
export { routeFor } from './src/lib/routes.ts';`,
    resolveDir: '.',
    loader: 'ts',
  },
  bundle: true,
  format: 'esm',
  platform: 'neutral',
  write: false,
  legalComments: 'none',
});
const body = `// GENERATED by scripts/build-relay-lib.mjs from src/lib/{where,support,routes}.ts. Do not edit.\n${result.outputFiles[0].text}`;
if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(OUT, 'utf8');
  } catch {
    // no bundle yet: treated as stale below
  }
  if (current !== body) {
    console.error(`${OUT} is stale: run node scripts/build-relay-lib.mjs`);
    process.exit(1);
  }
  console.log(`${OUT} is current`);
} else {
  writeFileSync(OUT, body);
  console.log(`wrote ${OUT} (${body.length} bytes)`);
}
